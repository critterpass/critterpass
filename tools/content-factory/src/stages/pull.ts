/**
 * Pull stage: copies the live (published) release of a kind into packages/content so the app
 * bundle and bake read it, and regenerates packages/content/src/current.ts to import every kind
 * that has a current release.
 */
import { readdirSync, existsSync } from 'node:fs';
import path from 'node:path';

import { CONTENT_KINDS, loadRelease, type ContentKind } from '@cp/content';

import { REPO_DIR, writeJson, writeText } from '../work';
import { StageError } from './state';

export const CONTENT_PACKAGE_DIR = path.join(REPO_DIR, 'packages', 'content');

export function writeCurrentRelease(
  kind: ContentKind,
  artifact: unknown,
  root = CONTENT_PACKAGE_DIR,
): number {
  if (artifact === undefined) throw new StageError(`no published ${kind} release to pull`);
  const release = loadRelease(artifact, kind);
  writeJson(path.join(root, 'releases', kind, 'current.json'), release);
  writeText(path.join(root, 'src', 'current.ts'), renderCurrentModule(root));
  return release.version;
}

const identifier = (kind: string) => kind.replace(/_([a-z])/gu, (_, c: string) => c.toUpperCase());

export function renderCurrentModule(root = CONTENT_PACKAGE_DIR): string {
  const releasesDir = path.join(root, 'releases');
  const present = existsSync(releasesDir)
    ? readdirSync(releasesDir).filter(
        (kind): kind is ContentKind =>
          (CONTENT_KINDS as readonly string[]).includes(kind) &&
          existsSync(path.join(releasesDir, kind, 'current.json')),
      )
    : [];
  present.sort();
  const imports = present.map(
    (kind) =>
      `import ${identifier(kind)} from '../releases/${kind}/current.json' with { type: 'json' };`,
  );
  const entries = present.map((kind) =>
    identifier(kind) === kind ? kind : `${kind}: ${identifier(kind)}`,
  );
  return `// Generated by \`pnpm content <kind> pull\` from the approved releases in releases/<kind>/current.json.
${imports.join('\n')}

import { loadRelease } from './load';
import type { ContentKind, Release } from './schemas/release';

/** The raw current release per kind shipped in this package (the app bundle and bake read these). */
export const CURRENT_RELEASES: Partial<Record<ContentKind, unknown>> = { ${entries.join(', ')} };

/** The current release of a kind, checksum-verified; undefined when none has been pulled yet. */
export function currentRelease<K extends ContentKind>(kind: K): Release<K> | undefined {
  const raw = CURRENT_RELEASES[kind];
  return raw === undefined ? undefined : loadRelease(raw, kind);
}
`;
}
