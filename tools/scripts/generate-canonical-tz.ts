import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

/**
 * Generates packages/domain/src/time/tz-aliases.ts: every IANA backward-compatibility link name
 * (the ids Apple and Android still report, such as Asia/Saigon or Asia/Calcutta, which are also
 * CLDR's own canonical ids) mapped to the canonical IANA zone it names.
 *
 * Input is the vendored tzdata in tools/scripts/fixtures/tzdata (`backward` and `etcetera`).
 * `--fetch` first refreshes that copy from https://data.iana.org/time-zones/tzdata-latest.tar.gz.
 *
 *   pnpm tsx tools/scripts/generate-canonical-tz.ts [--fetch]
 *
 * The `backward` section "Pre-2013 practice" is left out on purpose: those names (Europe/Oslo,
 * Europe/Amsterdam, Asia/Kuala_Lumpur, Atlantic/Reykjavik ...) are current zone.tab locations a
 * device reports as its own zone. IANA links them to another city with identical post-1970 clocks,
 * but rewriting a user's Oslo to Berlin would rename their place, and Postgres ships them as zones.
 */

export const TZDATA_DIR = path.resolve(import.meta.dirname, 'fixtures/tzdata');
export const OUTPUT_PATH = path.resolve(
  import.meta.dirname,
  '../../packages/domain/src/time/tz-aliases.ts',
);
const TZDATA_URL = 'https://data.iana.org/time-zones/tzdata-latest.tar.gz';
const KEPT_LOCATION_SECTION = /^# Pre-2013 practice\b/;

interface RawLink {
  readonly target: string;
  /** The `#= TARGET1` a link-to-link would name; preferred when it is itself a kept location. */
  readonly preferred: string | undefined;
}

/** Parses `Link TARGET LINK-NAME [#= TARGET1]` lines, skipping the kept-location section. */
export function parseLinks(
  source: string,
  options: { skipKeptLocations: boolean },
): Map<string, RawLink> {
  const links = new Map<string, RawLink>();
  let section = '';
  let previousBlank = true;
  for (const line of source.split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '') {
      previousBlank = true;
      continue;
    }
    if (trimmed.startsWith('#') && previousBlank && !trimmed.startsWith('# Link'))
      section = trimmed;
    previousBlank = false;
    const match = /^Link\s+(\S+)\s+(\S+)(?:\s+#=\s*(\S+))?/.exec(trimmed);
    if (match === null) continue;
    if (options.skipKeptLocations && KEPT_LOCATION_SECTION.test(section)) continue;
    const [, target, name, preferred] = match;
    if (target === undefined || name === undefined) continue;
    links.set(name, { target, preferred });
  }
  return links;
}

/** Resolves every alias to a name that is not itself an alias (links may point at links). */
export function buildTzAliases(backward: string, etcetera: string): Map<string, string> {
  const raw = new Map([
    ...parseLinks(backward, { skipKeptLocations: true }),
    ...parseLinks(etcetera, { skipKeptLocations: false }),
  ]);
  const resolved = new Map<string, string>();
  for (const [name, link] of [...raw].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    let current = link.preferred ?? link.target;
    const seen = new Set([name]);
    for (let next = raw.get(current); next !== undefined; next = raw.get(current)) {
      if (seen.has(current)) throw new Error(`tz link cycle through ${current}`);
      seen.add(current);
      current = next.preferred ?? next.target;
    }
    resolved.set(name, current);
  }
  return resolved;
}

export function renderTzAliases(version: string, aliases: ReadonlyMap<string, string>): string {
  const entries = [...aliases].map(([alias, canonical]) => `  ['${alias}', '${canonical}'],`);
  return [
    `// Generated by tools/scripts/generate-canonical-tz.ts from IANA tzdata ${version}; do not edit.`,
    '',
    '/** IANA tzdata release the alias table was generated from. */',
    `export const TZDATA_VERSION = '${version}';`,
    '',
    '/** Backward-compatibility time zone id -> canonical IANA id. */',
    'export const TZ_ALIASES: ReadonlyMap<string, string> = new Map([',
    ...entries,
    ']);',
    '',
  ].join('\n');
}

export function readVendoredTzdata(dir: string = TZDATA_DIR): {
  version: string;
  backward: string;
  etcetera: string;
} {
  const read = (file: string): string => readFileSync(path.join(dir, file), 'utf-8');
  return {
    version: read('version').trim(),
    backward: read('backward'),
    etcetera: read('etcetera'),
  };
}

function fetchLatestTzdata(): void {
  const work = mkdtempSync(path.join(tmpdir(), 'tzdata-'));
  try {
    const archive = path.join(work, 'tzdata.tar.gz');
    execFileSync('curl', ['-sSfL', '-o', archive, TZDATA_URL]);
    execFileSync('tar', ['-xzf', archive, '-C', work, 'version', 'backward', 'etcetera']);
    for (const file of ['version', 'backward', 'etcetera']) {
      copyFileSync(path.join(work, file), path.join(TZDATA_DIR, file));
    }
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function main(): void {
  if (process.argv.includes('--fetch')) fetchLatestTzdata();
  const { version, backward, etcetera } = readVendoredTzdata();
  const aliases = buildTzAliases(backward, etcetera);
  writeFileSync(OUTPUT_PATH, renderTzAliases(version, aliases));
  console.log(`wrote ${aliases.size} aliases from tzdata ${version} to ${OUTPUT_PATH}`);
}

if (import.meta.url === `file://${process.argv[1] ?? ''}`) main();
