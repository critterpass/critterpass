/**
 * Extracts the prototype's hand-drawn doodle icons (design/doodles.js, read-only) into static
 * vector path data for apps/mobile/src/ui/icons/generated. The prototype draws every icon at
 * runtime on a 2D canvas (Catmull-Rom splines → tapered brush ribbons with seeded wobble, offset
 * watercolour washes); this script runs that exact code headlessly, captures the op list its
 * `<doodle-art>` element builds, and bakes each op into an SVG path string that Skia draws as-is.
 * Colours are stored as design-token paths (never hex): `ink` and `accent` are roles the caller
 * sets, fixed colours snap to the nearest `color.*` token.
 *
 *   pnpm tsx tools/design-renders/extract-doodles.mjs          # write the generated files
 *   pnpm tsx tools/design-renders/extract-doodles.mjs --check  # fail if they are out of date
 *
 * Plain ESM like this package's other scripts; run through tsx because it reads the design tokens'
 * TypeScript source. The creature doodles (gecko, tanuki, …) are the guides: the sticker renderer draws those from
 * @cp/critter-art, so they are skipped here.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import * as prettier from 'prettier';
import { tokens } from '../../packages/design-tokens/src/index';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCE = path.join(ROOT, 'design/doodles.js');
const OUT_DIR = path.join(ROOT, 'apps/mobile/src/ui/icons/generated');
const INK = '@ink';
const ACCENT = '@accent';
/** Thinnest brush width in viewBox units (the prototype's 1.05 device px at a 48 pt icon). */
const MIN_WIDTH = 2;
/** Polygon simplification tolerance in viewBox units (0.12 of 100 ≈ invisible at 64 pt). */
const SIMPLIFY_EPSILON = 0.12;
const HEADER = [
  '// Generated by tools/design-renders/extract-doodles.mjs from design/doodles.js. Do not edit.',
  '/* eslint-disable lingui/no-unlocalized-strings -- vector path data and token paths, never copy. */',
].join('\n');
function loadDoodleKit() {
  const defined = new Map();
  const context = {
    window: {},
    customElements: {
      get: () => undefined,
      define: (name, ctor) => defined.set(name, ctor),
    },
    HTMLElement: class {},
  };
  vm.runInNewContext(readFileSync(SOURCE, 'utf8'), context);
  const kit = context.window.DoodleKit;
  const DoodleArt = defined.get('doodle-art');
  if (!DoodleArt) throw new Error('design/doodles.js no longer defines <doodle-art>');
  return { K: kit.K, creatures: new Set(Object.keys(kit.CREATURES)), DoodleArt };
}
function buildOps(DoodleArt, kind, accent) {
  const el = new DoodleArt();
  const attrs = { kind, size: '100', ink: INK, accent };
  el.cv = { style: {} };
  el.getAttribute = (name) => attrs[name] ?? null;
  el.setup();
  return el.opsOpen;
}
/** The prototype's seeded PRNG (mulberry32 variant), ported verbatim. */
function rng(seed) {
  let a = (seed * 1000003) >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
/** The prototype's `ribbon()` brush outline at full draw progress, as a closed polygon. */
function ribbon(P, o) {
  const n = P.length;
  const r = rng(o.seed);
  const ph = r() * 6.28;
  const ph2 = r() * 6.28;
  const Q = P.map((p, i) => [
    p[0] + Math.sin(i * 0.07 + ph) * o.amp,
    p[1] + Math.cos(i * 0.061 + ph2) * o.amp,
  ]);
  const L = [];
  const R = [];
  for (let i = 0; i < n; i++) {
    const a = Q[Math.max(0, i - 1)];
    const b = Q[Math.min(n - 1, i + 1)];
    const q = Q[i];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const m = Math.hypot(dx, dy) || 1;
    const nx = -dy / m;
    const ny = dx / m;
    const t = i / Math.max(1, n - 1);
    const press = o.close
      ? 0.78 + 0.22 * Math.sin(t * 6.28 * 2 + ph)
      : o.taper
        ? Math.pow(Math.max(0.02, Math.sin(Math.PI * (0.06 + 0.88 * t))), 0.5)
        : 1;
    const ww = Math.max(MIN_WIDTH, o.w * press * (0.9 + 0.2 * Math.sin(i * 0.19 + ph2))) / 2;
    L.push([q[0] + nx * ww, q[1] + ny * ww]);
    R.push([q[0] - nx * ww, q[1] - ny * ww]);
  }
  return [...L, ...R.reverse()];
}
function perpendicularDistance(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const m = Math.hypot(dx, dy);
  if (m === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / m;
}
/** Ramer–Douglas–Peucker simplification (keeps the brush silhouette, drops ~80 % of points). */
function simplify(points) {
  if (points.length < 3) return points;
  const first = points[0];
  const last = points[points.length - 1];
  let index = 0;
  let max = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpendicularDistance(points[i], first, last);
    if (d > max) {
      max = d;
      index = i;
    }
  }
  if (max <= SIMPLIFY_EPSILON) return [first, last];
  return [...simplify(points.slice(0, index + 1)).slice(0, -1), ...simplify(points.slice(index))];
}
const num = (v) => String(Math.round(v * 10) / 10);
function toPath(points, offset = [0, 0]) {
  const pts = simplify(points);
  return (
    pts
      .map((p, i) => `${i === 0 ? 'M' : 'L'}${num(p[0] + offset[0])} ${num(p[1] + offset[1])}`)
      .join('') + 'Z'
  );
}
function flattenColors(node, prefix, out) {
  if (typeof node === 'string' && node.startsWith('#')) out.set(prefix, node.toLowerCase());
  else if (node && typeof node === 'object')
    for (const [k, v] of Object.entries(node)) flattenColors(v, `${prefix}.${k}`, out);
}
const COLOR_TOKENS = new Map();
flattenColors(tokens.color, 'color', COLOR_TOKENS);
function rgb(hex) {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}
/** Snaps a prototype colour to the nearest `color.*` token (exact match when the design uses one). */
function tokenFor(hex) {
  const target = rgb(hex);
  let best = '';
  let bestDistance = Number.POSITIVE_INFINITY;
  for (const [name, value] of COLOR_TOKENS) {
    const c = rgb(value);
    const d = (c[0] - target[0]) ** 2 + (c[1] - target[1]) ** 2 + (c[2] - target[2]) ** 2;
    if (d < bestDistance) {
      bestDistance = d;
      best = name;
    }
  }
  return best;
}
function paintFor(color) {
  if (color === INK) return 'ink';
  if (color === ACCENT) return 'accent';
  return tokenFor(color);
}
function samePoints(a, b) {
  return a.length === b.length && a.every((p, i) => p[0] === b[i]?.[0] && p[1] === b[i]?.[1]);
}
function layersFor(ops) {
  const back = [];
  const front = [];
  for (const op of ops) {
    if (op.t === 'wash') {
      const r = rng(op.seed);
      const offset = [(r() - 0.5) * 2 * op.off, (r() - 0.2) * op.off];
      back.push({
        d: toPath(op.P, offset),
        paint: paintFor(op.color),
        opacity: op.al,
        multiply: true,
      });
    } else if (op.t === 'under') {
      back.push({
        d: toPath(ribbon(op.P, op.o)),
        paint: paintFor(op.o.color),
        opacity: 0.9,
        multiply: true,
      });
    } else if (op.t === 'fill') {
      front.push({
        d: toPath(op.P),
        paint: paintFor(op.color),
        ...(op.al !== undefined && op.al !== 1 ? { opacity: op.al } : {}),
      });
    } else {
      front.push({ d: toPath(ribbon(op.P, op.o)), paint: paintFor(op.o.color) });
    }
  }
  return [...back, ...front];
}
function defaultAccentFor(accented, plain) {
  for (const op of accented) {
    const color = op.t === 'line' || op.t === 'under' ? op.o.color : op.color;
    if (color !== ACCENT) continue;
    const twin = plain.find((candidate) => samePoints(candidate.P, op.P));
    if (!twin) continue;
    const twinColor = twin.t === 'line' || twin.t === 'under' ? twin.o.color : twin.color;
    if (twinColor !== INK) return tokenFor(twinColor);
  }
  return undefined;
}
async function format(file, source) {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(source, { ...config, filepath: file });
}
async function generate() {
  const { K, creatures, DoodleArt } = loadDoodleKit();
  const kinds = Object.keys(K)
    .filter((kind) => !creatures.has(kind))
    .sort();
  const files = new Map();
  for (const kind of kinds) {
    const fn = K[kind];
    const accented = buildOps(DoodleArt, kind, ACCENT);
    const plain = buildOps(DoodleArt, kind, null);
    const defaultAccent = defaultAccentFor(accented, plain);
    const def = {
      viewBox: fn.vb ?? [100, 100],
      ...(defaultAccent ? { defaultAccent } : {}),
      layers: layersFor(accented),
    };
    const file = path.join(OUT_DIR, `${kind}.ts`);
    const source = `${HEADER}\nimport type { DoodleDef } from '../types';\n\nexport const ${kind}Doodle: DoodleDef = ${JSON.stringify(def)};\n`;
    files.set(file, await format(file, source));
  }
  const index = path.join(OUT_DIR, 'index.ts');
  const imports = kinds.map((kind) => `import { ${kind}Doodle } from './${kind}';`).join('\n');
  const entries = kinds.map((kind) => `  ${kind}: ${kind}Doodle,`).join('\n');
  const indexSource = `${HEADER.split('\n')[0]}\n${imports}\n\n/** Every extracted doodle icon, keyed by its design/doodles.js kind. */\nexport const DOODLES = {\n${entries}\n} as const;\n\nexport type DoodleName = keyof typeof DOODLES;\n`;
  files.set(index, await format(index, indexSource));
  return files;
}
async function main() {
  const check = process.argv.includes('--check');
  const files = await generate();
  const existing = existsSync(OUT_DIR)
    ? readdirSync(OUT_DIR).map((name) => path.join(OUT_DIR, name))
    : [];
  if (check) {
    const stale = [...files].filter(
      ([file, source]) => !existsSync(file) || readFileSync(file, 'utf8') !== source,
    );
    const extra = existing.filter((file) => !files.has(file));
    for (const [file] of stale) console.error(`out of date: ${path.relative(ROOT, file)}`);
    for (const file of extra) console.error(`not generated: ${path.relative(ROOT, file)}`);
    if (stale.length > 0 || extra.length > 0) {
      console.error(
        'Run `pnpm tsx tools/design-renders/extract-doodles.mjs` and commit the result.',
      );
      process.exit(1);
    }
    console.log(`${files.size - 1} doodles up to date.`);
    return;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  for (const file of existing) if (!files.has(file)) rmSync(file);
  for (const [file, source] of files) writeFileSync(file, source);
  console.log(`Wrote ${files.size - 1} doodles to ${path.relative(ROOT, OUT_DIR)}.`);
}
await main();
