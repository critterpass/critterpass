/**
 * Generates the Swift and Kotlin types for the App Group files (docs/code-standards.md §14:
 * snapshot schemas in `packages/domain` → generated native types) from the zod schemas in
 * src/surfaces/app-group.ts, into the cp-app-group module both platforms compile.
 *
 *   pnpm --filter @cp/domain exec tsx scripts/gen-surfaces.ts          # write
 *   pnpm --filter @cp/domain exec tsx scripts/gen-surfaces.ts --check  # fail on drift
 *
 * Covers the zod subset these contracts use: objects, strings (any format, kept as text so ISO
 * timestamps round-trip exactly), integers, numbers, booleans, literals, string enums, arrays,
 * optional/nullable fields, string-keyed records and free-form JSON.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import type { z } from 'zod';

import {
  endpointsConfigSchema,
  pendingActionSchema,
  pendingActionsFileSchema,
} from '../src/surfaces/app-group';
import { renderKotlin } from './surface-kotlin';
import { buildModels, camel, type Field, type SurfaceModels } from './surface-model';

/** Top-level types, in output order; nested object schemas must be listed here to get a name. */
const TYPES: readonly (readonly [string, z.ZodType])[] = [
  ['PendingAction', pendingActionSchema],
  ['PendingActionsFile', pendingActionsFileSchema],
  ['EndpointsConfig', endpointsConfigSchema],
];

const MODULE_DIR = path.resolve(import.meta.dirname, '../../../apps/mobile/modules/cp-app-group');
const SWIFT_OUT = path.join(MODULE_DIR, 'ios/AppGroupSurfaces.swift');
const KOTLIN_OUT = path.join(
  MODULE_DIR,
  'android/src/main/java/app/critterpass/appgroup/AppGroupSurfaces.kt',
);
const HEADER =
  '// Generated by packages/domain/scripts/gen-surfaces.ts from src/surfaces/app-group.ts. Do not edit.';

// --- Swift -------------------------------------------------------------------------------------

function swiftType(field: Field): string {
  switch (field.kind) {
    case 'string':
      return 'String';
    case 'int':
      return 'Int';
    case 'double':
      return 'Double';
    case 'bool':
      return 'Bool';
    case 'json':
      return 'JSONValue';
    case 'literal':
      return typeof field.value === 'number' ? 'Int' : 'String';
    case 'enum':
    case 'object':
      return field.name;
    case 'array':
      return `[${swiftType(field.of)}]`;
    case 'record':
      return `[String: ${swiftType(field.of)}]`;
  }
}

function renderSwift({ models, enums }: SurfaceModels): string {
  const out = [HEADER, '', 'import Foundation', ''];
  for (const [name, values] of enums) {
    out.push(`public enum ${name}: String, Codable, Hashable, Sendable {`);
    for (const value of values) out.push(`  case ${camel(value)} = "${value}"`);
    out.push('}', '');
  }
  for (const model of models) {
    out.push(`public struct ${model.name}: Codable, Hashable, Sendable {`);
    for (const prop of model.props) {
      if (prop.field.kind === 'literal') {
        out.push(
          `  public static let ${prop.name}Value: ${swiftType(prop.field)} = ${JSON.stringify(prop.field.value)}`,
        );
      }
    }
    for (const prop of model.props) {
      out.push(`  public var ${prop.name}: ${swiftType(prop.field)}${prop.optional ? '?' : ''}`);
    }
    out.push('', '  enum CodingKeys: String, CodingKey {');
    for (const prop of model.props) out.push(`    case ${prop.name} = "${prop.wire}"`);
    out.push('  }', '}', '');
  }
  out.push(
    '/// Free-form JSON (command payloads): decodes and re-encodes any JSON value unchanged.',
    'public enum JSONValue: Codable, Hashable, Sendable {',
    '  case string(String)',
    '  case number(Double)',
    '  case bool(Bool)',
    '  case object([String: JSONValue])',
    '  case array([JSONValue])',
    '  case null',
    '',
    '  public init(from decoder: Decoder) throws {',
    '    let container = try decoder.singleValueContainer()',
    '    if container.decodeNil() { self = .null }',
    '    else if let value = try? container.decode(Bool.self) { self = .bool(value) }',
    '    else if let value = try? container.decode(Double.self) { self = .number(value) }',
    '    else if let value = try? container.decode(String.self) { self = .string(value) }',
    '    else if let value = try? container.decode([JSONValue].self) { self = .array(value) }',
    '    else { self = .object(try container.decode([String: JSONValue].self)) }',
    '  }',
    '',
    '  public func encode(to encoder: Encoder) throws {',
    '    var container = encoder.singleValueContainer()',
    '    switch self {',
    '    case .string(let value): try container.encode(value)',
    '    case .number(let value): try container.encode(value)',
    '    case .bool(let value): try container.encode(value)',
    '    case .object(let value): try container.encode(value)',
    '    case .array(let value): try container.encode(value)',
    '    case .null: try container.encodeNil()',
    '    }',
    '  }',
    '}',
    '',
  );
  return out.join('\n');
}

function main(): void {
  const models = buildModels(TYPES);
  const check = process.argv.includes('--check');
  const outputs: [string, string][] = [
    [SWIFT_OUT, renderSwift(models)],
    [KOTLIN_OUT, renderKotlin(HEADER, models)],
  ];
  const stale: string[] = [];
  for (const [file, content] of outputs) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // not generated yet
    }
    if (current === content) continue;
    if (check) stale.push(path.relative(process.cwd(), file));
    else writeFileSync(file, content);
  }
  if (stale.length > 0) {
    process.stderr.write(`stale generated surfaces (run gen-surfaces.ts): ${stale.join(', ')}\n`);
    process.exit(1);
  }
}

main();
