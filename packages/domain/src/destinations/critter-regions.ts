/**
 * Where each critter lives, for matching base-set destinations to their nearest critter: the
 * centre of its city, region or single place (the Mekong delta, Borneo, Keukenhof, Sidi Bou Said),
 * keyed by critter key. A hand-kept code table: a new critter adds a line here.
 *
 * `CRITTER_ADMIN_OVERRIDES` sends every destination of a first-level region (GeoNames admin1 name)
 * to one critter where distance misleads: Kalimantan and Malaysian Borneo belong to the Borneo
 * critter, not Bali's; Hawaii to Honolulu's; south China's karst to Guilin's.
 */

