import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

// Reads the unmodified design/critters-data.js (read-only source) and writes typed, checked-in
// data: src/data/places.ts (61 places) and src/data/critters.ts (150 critters, 6 guides + 144
// locals). Re-run after any content-factory change to critters-data.js; idempotent (same input
// always produces the same output).

const repoRoot = new URL('../../../', import.meta.url);
const dataDir = new URL('../src/data/', import.meta.url);

function readDesignFile(name: string): string {
  return readFileSync(new URL(`design/${name}`, repoRoot), 'utf8');
}

interface DesignCritter {
  readonly id: string;
  readonly no: number;
  readonly num: string;
  readonly name: string;
  readonly species: string;
  readonly city: string;
  readonly place: string;
  readonly code: string;
  readonly tier: number;
  readonly rank: number | null;
  readonly spec: Record<string, unknown>;
  readonly kind: string;
}

interface DesignPlace {
  readonly code: string;
  readonly name: string;
  readonly tier: number;
  readonly rank: number | null;
  readonly rk: string;
  readonly critters: readonly DesignCritter[];
}

interface DesignCritterDex {
  readonly places: readonly DesignPlace[];
  readonly list: readonly DesignCritter[];
}

function loadCritterDex(): DesignCritterDex {
  const sandbox: { window?: unknown; CritterDex?: DesignCritterDex } = {};
  sandbox.window = sandbox;
  const context = vm.createContext(sandbox);
  new vm.Script(readDesignFile('critters-data.js'), { filename: 'critters-data.js' }).runInContext(
    context,
  );
  if (!sandbox.CritterDex) throw new Error('design/critters-data.js did not set window.CritterDex');
  return sandbox.CritterDex;
}

function writeGenerated(
  fileName: string,
  typeName: 'Place' | 'Critter',
  exportName: string,
  rows: readonly unknown[],
): void {
  const lines = rows.map((row) => `  ${JSON.stringify(row)},`);
  const content = [
    '// Generated by scripts/import-design-data.ts from design/critters-data.js. Do not hand-edit.',
    `import type { ${typeName} } from './types';`,
    '',
    `export const ${exportName}: readonly ${typeName}[] = [`,
    ...lines,
    '];',
    '',
  ].join('\n');
  writeFileSync(new URL(fileName, dataDir), content);
}

function main(): void {
  const dex = loadCritterDex();

  // design's `tier` is the place's set size (C4); renamed `setGroup` here to avoid colliding with
  // the form tier (common/rare/epic/legendary, `FormSpec.rarity`) the rest of the package uses.
  const places = dex.places.map((place) => ({
    code: place.code,
    name: place.name,
    setGroup: place.tier,
    rank: place.rank,
    rk: place.rk,
    critterIds: place.critters.map((c) => c.id),
  }));

  const critters = dex.list.map((c) => ({
    id: c.id,
    no: c.no,
    num: c.num,
    name: c.name,
    species: c.species,
    city: c.city,
    place: c.place,
    code: c.code,
    setGroup: c.tier,
    rank: c.rank,
    spec: c.spec,
    kind: c.kind,
  }));

  writeGenerated('places.ts', 'Place', 'places', places);
  writeGenerated('critters.ts', 'Critter', 'critters', critters);

  console.log(`imported ${places.length} places, ${critters.length} critters`);
}

main();
