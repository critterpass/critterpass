  FOR EACH ROW EXECUTE FUNCTION app.canonicalize_timezone();
CREATE TRIGGER scheduled_events_canonical_tz BEFORE INSERT OR UPDATE OF tz ON scheduled_events
  FOR EACH ROW EXECUTE FUNCTION app.canonicalize_tz();
