-- The shape check (Area/Location segments, or an Etc/GMT offset) rules out what the timestamptz
-- parser would otherwise accept as a zone: abbreviations (ICT), POSIX strings (UTC+3) and ids with
-- an offset suffix (Asia/Tokyo+5). pg_input_is_valid then resolves the name against the server's
-- tzdata without raising, so no subtransaction is needed. Stored ids must already be canonical;
-- the triggers below canonicalize before the CHECK runs.
CREATE OR REPLACE FUNCTION app.valid_tz(tz text) RETURNS boolean
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT tz OPERATOR(pg_catalog.~)
           '^(Etc/GMT(-(1[0-4]|[1-9])|\+(1[0-2]|[1-9]))|[A-Z][A-Za-z_-]*(/[A-Z][A-Za-z_-]*){1,2})$'
     AND app.canonical_tz(tz) OPERATOR(pg_catalog.=) tz
     AND pg_catalog.pg_input_is_valid('2000-01-01 00:00:00 ' OPERATOR(pg_catalog.||) tz,
                                      'pg_catalog.timestamptz')
$$;

CREATE OR REPLACE FUNCTION app.canonicalize_tz() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  NEW.tz := app.canonical_tz(NEW.tz);
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION app.canonicalize_timezone() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  NEW.timezone := app.canonical_tz(NEW.timezone);
  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION app.canonical_tz(text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION app.canonicalize_tz() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION app.canonicalize_timezone() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.canonical_tz(text) TO app_user, app_system;
GRANT EXECUTE ON FUNCTION app.canonicalize_tz() TO app_user, app_system;
GRANT EXECUTE ON FUNCTION app.canonicalize_timezone() TO app_user, app_system;

CREATE TRIGGER users_canonical_tz BEFORE INSERT OR UPDATE OF tz ON users
  FOR EACH ROW EXECUTE FUNCTION app.canonicalize_tz();
