-- Time zone ids: validate without scanning pg_timezone_names, and store only canonical IANA ids.
--
-- app.valid_tz used to look the id up in pg_timezone_names, which reads every zone file on disk on
-- each call (milliseconds per row inside the tz CHECK constraints), and it rejected the IANA
-- backward-compatibility links Apple platforms report as CLDR ids (Asia/Saigon, Asia/Calcutta,
-- Asia/Katmandu) on Postgres builds whose tzdata leaves those links to tzdata-legacy.
--
-- app.canonical_tz maps those links to the zone they name, and BEFORE triggers apply it to every tz
-- column, so direct SQL writers (apply_change_set, admin tools, seeds) store canonical ids just like
-- the API and worker, which canonicalize with @cp/domain's canonicalTz. The jsonb object is the same
-- table as packages/domain/src/time/tz-aliases.ts (IANA tzdata 2026d), generated by
-- tools/scripts/generate-canonical-tz.ts; packages/db/test/valid-tz.test.ts checks they agree.

-- Both functions are single-expression SQL without a SET clause so the planner inlines them into
-- the CHECK constraints and triggers (a pinned search_path would force a per-call function
-- invocation with a GUC save/restore); every operator and function is schema-qualified instead,
-- so a caller's search_path cannot shadow them. The jsonb literal is parsed once per plan and
-- `->>` is a binary search over its keys.
